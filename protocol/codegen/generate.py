#!/usr/bin/env python3
"""Generates per-language protocol stubs from protocol/schema/*.yaml +
protocol/methods.yaml. See protocol/README.md.

Usage:
    python protocol/codegen/generate.py --lang python
    python protocol/codegen/generate.py --lang cpp
    python protocol/codegen/generate.py --lang rust
    python protocol/codegen/generate.py --lang python cpp rust   # all
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Callable

sys.path.insert(0, str(Path(__file__).resolve().parent))

import jinja2

import cpprender
import pyrender
import rustrender
import schema_ir

CODEGEN_DIR = Path(__file__).resolve().parent
PROTOCOL_DIR = CODEGEN_DIR.parent
REPO_ROOT = PROTOCOL_DIR.parent

PYTHON_OUT = REPO_ROOT / "backends" / "py-rpc-common" / "rpc_common" / "generated"
CPP_OUT = REPO_ROOT / "fronts" / "qt" / "generated"
RUST_OUT = REPO_ROOT / "backends" / "spotify" / "src" / "generated"


def _env(lang: str) -> jinja2.Environment:
    env = jinja2.Environment(
        loader=jinja2.FileSystemLoader(str(CODEGEN_DIR / "templates" / lang)),
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    env.filters["tojson"] = json.dumps
    return env


def _write_changed(out: Path, files: dict[str, str], format_files: Callable[[list[Path]], None] | None = None) -> None:
    """Writes `files` ({name: text}) into `out`, formatted, touching only
    those whose content changed: a rewritten file with the same content
    still makes cargo, CMake and the like rebuild everything depending on
    it. Rendered and formatted in a scratch directory next to `out`, so the
    formatter finds the same config file (_clang-format, rustfmt.toml) by
    walking up as it would for `out` itself."""
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".generate-", dir=out.parent) as scratch:
        paths = []
        for name, text in files.items():
            path = Path(scratch) / name
            path.write_text(text)
            paths.append(path)
        if format_files is not None:
            format_files(paths)
        changed = []
        for path in paths:
            target = out / path.name
            new = path.read_bytes()
            if not target.exists() or target.read_bytes() != new:
                target.write_bytes(new)
                changed.append(path.name)
    print(f"{out}: " + (f"wrote {', '.join(changed)}" if changed else "up to date"))


def generate_python(ir: schema_ir.ProtocolIR) -> None:
    ctx = pyrender.render_context(ir)
    env = _env("python")
    _write_changed(
        PYTHON_OUT,
        {
            "__init__.py": '"""AUTO-GENERATED by protocol/codegen/generate.py — do not edit by hand."""\n',
            "models.py": env.get_template("models.py.jinja").render(ctx),
            "methods.py": env.get_template("methods.py.jinja").render(ctx),
        },
    )


def _clang_format_inplace(paths: list[Path]) -> None:
    """Applies fronts/qt/_clang-format (see fronts/qt/AGENTS.md) to generated C++ output
    so generated/ matches the same house style as hand-written code —
    clang-format finds it by walking up from each file's directory, same as
    it would for any other file under fronts/qt/."""
    clang_format = shutil.which("clang-format")
    if clang_format is None:
        print("warning: clang-format not found on PATH — generated C++ left unformatted", file=sys.stderr)
        return
    subprocess.run([clang_format, "-i", *[str(p) for p in paths]], check=True)


def generate_cpp(ir: schema_ir.ProtocolIR) -> None:
    ctx = cpprender.render_context(ir)
    env = _env("cpp")
    _write_changed(
        CPP_OUT,
        {
            "Models.h": env.get_template("Models.h.jinja").render(ctx),
            "RpcMethods.h": env.get_template("RpcMethods.h.jinja").render(ctx),
            "RpcMethods.cpp": env.get_template("RpcMethods.cpp.jinja").render(ctx),
        },
        _clang_format_inplace,
    )


def _rustfmt_inplace(paths: list[Path]) -> None:
    """Formats generated Rust like hand-written code; optional, same as
    clang-format for the C++ target. A failing rustfmt counts as missing:
    rustup puts a `rustfmt` on PATH that only errors out when the component
    isn't installed (the rust:alpine image)."""
    rustfmt = shutil.which("rustfmt")
    result = None
    if rustfmt is not None:
        result = subprocess.run([rustfmt, "--edition", "2021", *[str(p) for p in paths]], capture_output=True)
    if result is None or result.returncode != 0:
        print("warning: rustfmt not usable — generated Rust left unformatted", file=sys.stderr)


def generate_rust(ir: schema_ir.ProtocolIR) -> None:
    ctx = rustrender.render_context(ir)
    env = _env("rust")
    _write_changed(
        RUST_OUT,
        {
            "mod.rs": "// AUTO-GENERATED by protocol/codegen/generate.py — do not edit by hand.\n\n"
            "pub mod methods;\npub mod models;\n",
            "models.rs": env.get_template("models.rs.jinja").render(ctx),
            "methods.rs": env.get_template("methods.rs.jinja").render(ctx),
        },
        _rustfmt_inplace,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lang", nargs="+", choices=["python", "cpp", "rust"], required=True)
    args = parser.parse_args()

    ir = schema_ir.build()

    if "python" in args.lang:
        generate_python(ir)
    if "cpp" in args.lang:
        generate_cpp(ir)
    if "rust" in args.lang:
        generate_rust(ir)


if __name__ == "__main__":
    main()
